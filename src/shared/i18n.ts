/** UI strings only: never translate authored Markdown, HTML, labels or paths. */
export type Language = 'zh-CN' | 'en';
export function resolveLanguage(setting:unknown, vscodeLanguage?:string, systemLanguage?:string):Language {
  const requested=setting==='auto'||!setting ? vscodeLanguage||systemLanguage||'en' : setting;
  return typeof requested==='string'&&/^zh(?:[-_]|$)/i.test(requested)?'zh-CN':'en';
}
let language:Language=typeof document==='undefined'?'zh-CN':resolveLanguage('auto',document.documentElement.lang,navigator.language);
export function setLanguage(value:Language){language=value;}
export function getLanguage(){return language;}
export function t(key:keyof typeof english,values:Record<string,string|number>={}):string {
  const text=language==='en'?english[key]:key;
  return text.replace(/\{(\w+)\}/g,(match,name)=>Object.hasOwn(values,name)?String(values[name]):match);
}
